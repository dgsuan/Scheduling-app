// Copies the app's pure scheduling logic into supabase/functions/_shared/app
// so the Edge Functions use exactly the same rules as the app (reminders,
// holidays, term dates, calendar import). Rewrites "@/…" imports to relative
// ".ts" paths and fails loudly if a copied file imports anything else (like
// React Native), which the server can't run.
//   node scripts/prepare-functions.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(APP, "supabase", "functions", "_shared", "app");

/** Source (relative to the app) → file name in _shared/app. */
const FILES = {
  "lib/dates.ts": "dates.ts",
  "lib/schedule.ts": "schedule.ts",
  "lib/tasks.ts": "tasks.ts",
  "lib/reminders.ts": "reminders.ts",
  "lib/ics.ts": "ics.ts",
  "lib/icsMerge.ts": "icsMerge.ts",
  "lib/grades.ts": "grades.ts",
  "lib/semester.ts": "semester.ts",
  "lib/recurrence.ts": "recurrence.ts",
  "constants/holidays.ts": "holidays.ts",
};

const SPECIFIERS = {
  "@/context/store": "./store-types.ts",
  ...Object.fromEntries(Object.entries(FILES).map(([src, out]) => [`@/${src.replace(/\.ts$/, "")}`, `./${out}`])),
};

const HEADER = "// Generated by scripts/prepare-functions.mjs from the app's source. Don't edit — edit the original and re-run.\n";

function rewrite(file, code) {
  return code.replace(/(from\s+|import\s+)(["'])([^"']+)\2/g, (whole, lead, quote, spec) => {
    if (!spec.startsWith("@/") && !spec.startsWith(".")) {
      throw new Error(`${file} imports "${spec}", which the Edge Functions can't load. Keep shared logic free of app/UI imports.`);
    }
    const mapped = SPECIFIERS[spec];
    if (!mapped) throw new Error(`${file} imports "${spec}", which isn't copied for the Edge Functions. Add it to FILES in scripts/prepare-functions.mjs.`);
    return `${lead}${quote}${mapped}${quote}`;
  });
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

for (const [src, out] of Object.entries(FILES)) {
  const code = fs.readFileSync(path.join(APP, src), "utf8");
  fs.writeFileSync(path.join(OUT, out), HEADER + rewrite(src, code));
}

// The data types (and the two plain constants beside them) from the store,
// without the React provider around them.
const store = fs.readFileSync(path.join(APP, "context", "store.tsx"), "utf8");
const start = store.indexOf("export type Weekday");
const end = store.indexOf("// --- Store shape");
if (start < 0 || end < start) throw new Error("Couldn't find the data types in context/store.tsx.");
const types = store.slice(start, end);
const needsArchive = /\bArchivedTerm\b/.test(types);
fs.writeFileSync(
  path.join(OUT, "store-types.ts"),
  HEADER + (needsArchive ? 'import type { ArchivedTerm } from "./semester.ts";\n\n' : "") + types
);

console.log(`prepare-functions: copied ${Object.keys(FILES).length + 1} files to ${path.relative(APP, OUT)}`);
