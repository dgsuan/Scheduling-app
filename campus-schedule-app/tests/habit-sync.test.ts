import assert from 'node:assert/strict';
import { planHabitSync, habitRows, canAccessHabits, habitCacheKey, portableHabits, type HabitCloudRow } from '../lib/habitSync.ts';
import { type HabitData, type Habit } from '../lib/habits.ts';
const ownerId = '00000000-0000-0000-0000-000000000001';
const habit: Habit = { id: 'h1', title: 'Read', type: 'quantity', category: '', notes: '', createdAt: 1, reminder: false, schedules: [{ id: 's1', from: '2026-11-08', timezone: 'UTC', slots: ['00:00'], frequency: 'daily', interval: 1, quota: 3, weekdays: [1], weekStart: 1, target: 10, unit: 'pages', state: 'active' }] };
const initial: HabitData = { version: 1, habits: [habit], logs: [], cloud: { ownerId, base: {} } };
const remote = habitRows(initial).map(r => ({ ...r, updated_at: '2026-11-08T10:00:00Z' }));
const synced = planHabitSync(initial, remote).data;
assert.equal(planHabitSync(initial, []).uploads.length, 1);
assert.equal(planHabitSync(synced, remote).uploads.length, 0);
const log = (id: string) => ({ id, habitId: 'h1', occurrenceKey: 'h1:s1:2026-11-08:00:00', date: '2026-11-08', at: 1, amount: 2, confirmed: false });
const deviceA = { ...synced, logs: [log('a')] };
const deviceB = [...remote, { collection: 'habit_log' as const, id: 'b', parent: 'h1', data: log('b'), deleted: false, updated_at: '2026-11-08T11:00:00Z' }];
const merged = planHabitSync(deviceA, deviceB);
assert.deepEqual(merged.data.logs.map(l => l.id).sort(), ['a', 'b']);
assert.deepEqual(merged.uploads.map(u => u.row.id), ['a']);
assert.equal(planHabitSync(merged.data, [...deviceB, { ...merged.uploads[0].row, updated_at: '2026-11-08T12:00:00Z' }]).uploads.length, 0);
const localEdit = { ...synced, habits: [{ ...habit, title: 'Read locally' }] };
const cloudEdit = remote.map(r => ({ ...r, data: { ...habit, title: 'Read remotely' }, updated_at: '2026-11-08T13:00:00Z' }));
assert.equal(planHabitSync(localEdit, cloudEdit).conflicts.length, 1);
assert.equal(planHabitSync(localEdit, cloudEdit).uploads.length, 0);
assert.equal(planHabitSync(synced, cloudEdit).data.habits[0].title, 'Read remotely');
assert.equal(planHabitSync(localEdit, remote).uploads[0].expected, remote[0].updated_at);
const deleted = remote.map(r => ({ ...r, deleted: true, data: {} as Habit }));
assert.equal(planHabitSync(deviceA, deleted).data.habits.length, 0);
assert.equal(planHabitSync(deviceA, deleted).data.logs.length, 0);
assert.equal(planHabitSync(deviceA, deleted).uploads.length, 0);
const localDelete = { ...synced, habits: [], logs: [] };
assert.equal(planHabitSync(localDelete, remote).uploads[0].row.deleted, true);
assert.throws(() => planHabitSync(synced, []), /missing/);
const correction = { ...log('undo'), amount: 0, retracts: 'a' };
const ordered = planHabitSync({ ...initial, logs: [correction, log('a')] }, []).uploads;
assert.deepEqual(ordered.map(u => u.row.id), ['h1', 'a', 'undo']);
assert.equal(canAccessHabits(initial, ownerId), true);
assert.equal(canAccessHabits(initial, null), false);
assert.equal(canAccessHabits(initial, 'someone-else'), false);
assert.notEqual(habitCacheKey(ownerId), habitCacheKey());
assert.equal(portableHabits(initial).cloud, undefined);
console.log('PASS habit event union, replay, CAS plans, visible conflicts, deletion precedence, upload ordering, account scope and portable backup');
